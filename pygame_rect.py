import pygame as pg
pg.init()

BLACK = (0, 0, 0)
WHITE = (255, 255, 255)
RED = (255, 0, 0)
GREEN = (0, 255, 0)
BLUE = (0, 0, 255)
YELLOW = (255, 255, 0)
PURPLE = (255, 0, 255)
ORANGE = (255, 128, 0)

# Создаём окно.
w, h = 1200, 800
screen = pg.display.set_mode((w, h))
pg.display.set_caption("Прямоугольные области — Rect")
screen.fill(WHITE)
clock = pg.time.Clock()


# --------------------------------------------------
# 1. Картинка и её прямоугольная область
# --------------------------------------------------

# Картинки ограничены экземплярами класса Rect, как и любые другие поверхности, поэтому мы можем работать с расположением
# картинок при помощи различных атрибутов и методов данного класса.
fox = pg.image.load('images/fox.png')  # размер: 111x200
screen.blit(fox, (w // 2, 0))

# Rect хранит четыре основных значения:
# x, y — координаты левого верхнего угла;
# width, height — ширину и высоту.

# Сам по себе Rect ничего не рисует. Он помогает хранить положение, перемещать объекты и проверять их пересечения.
# При помощи метода get_rect() мы можем получить размеры прямоугольной области для любого объекта в игре:
# для поверхности, картинки, объекта модуля draw и т.д.

# Получаем новый Rect размером с картинку.
rct_image = fox.get_rect()
print("Rect картинки:", rct_image)  # => Rect картинки: <rect(0, 0, 111, 200)>
# Получили не конкретные числа, а объект класса Rect, который ограничивает нашу картинку.
# По умолчанию его левый верхний угол находится в (0, 0) а ширина и высота области соответствуют размерам картинки

# Давайте ограничим эту область rct_image контуром (нарисуем по её границе прямоугольник при помощи метода draw.rect)
# чтобы её местоположение было видно
pg.draw.rect(screen, BLACK, rct_image, 3)  # здесь область rct_image как раз и задаёт координаты нашего прямоугольника

# Чтобы получить конкретные числа (значения), нужно обратиться к атрибутам объекта.
# У любого объекта класса Rect есть свойства (атрибуты), хранящие информацию о его размерах и положении

# --------------------------------------------------
# 2. Атрибуты класса Rect - свойства прямоугольных областей
# --------------------------------------------------

print("Размер:", rct_image.size)   # => (111, 200)
print("Ширина:", rct_image.width)   # => 111
print("Высота:", rct_image.height)   # => 200

# Координаты центра хранятся как целые числа.
print("Центр:", rct_image.center)   # => (55, 100)

# Положение сторон.
print("Низ:", rct_image.bottom)  # => 200 - нижняя сторона области (наибольшая координата y)
print("Верх:", rct_image.top)  # => 0 - верхняя сторона области (наименьшая координата y)
print("Правая сторона:", rct_image.right)  # => 111 - правая сторона области (наибольшая координата x)
print("Левая сторона:", rct_image.left)  # => 0 - левая сторона области (наименьшая координата x)

# Координаты углов.
print("Левый верхний:", rct_image.topleft)      # => (0, 0)
print("Правый верхний:", rct_image.topright)    # => (111, 0)
print("Левый нижний:", rct_image.bottomleft)    # => (0, 200)
print("Правый нижний:", rct_image.bottomright)  # => (111, 200)


# Можно менять положение через атрибуты. Размер прямоугольника при этом не изменяется.
# Сдвинем центр нашей области в центр окна и отобразим на экране
rct_image.center = (w // 2, h // 2)

pg.draw.rect(screen, RED, rct_image, 3)

# Другие примеры:
# rct_image.x = 100
# rct_image.y = 50
# rct_image.topleft = (50, 40)

# Положение можно указать и сразу при создании Rect:
# rct_image = fox.get_rect(center = (w // 2, h // 2))

# А теперь давайте ограничим рамкой саму картинку
rct_image.topleft = (w // 2, 0)
pg.draw.rect(screen, RED, rct_image, 3)

# --------------------------------------------------
# 3. Методы класса Rect на примере двух прямоугольных областей rect1 и rect2
# --------------------------------------------------

# У каждой прямоугольной области есть методы для перемещения, изменения или объединения с другими областями
# Рассмотрим в качестве примера две прямоугольные области
rect1 = pg.Rect((0, h // 2, 150, 150))
rect2 = pg.Rect((200, h // 2, 250, 100))

print("\nИсходные прямоугольники:")
print("rect1:", rect1)
print("rect2:", rect2)

# Давайте ограничим эти области контуром (нарисуем по их границе прямоугольники при помощи метода draw.rect)
# чтобы их местоположение было видно
pg.draw.rect(screen, GREEN, rect1, 3)
pg.draw.rect(screen, ORANGE, rect2, 3)  # здесь rect1 и rect2 сами по себе задают координаты наших фигур

# Рассмотрим некоторые методы объектов класса Rect

# 1. Создаём новый прямоугольник размера rect1, но смещённый по x на 100px и по y на 200px
rect3 = rect1.move(100, 200)
pg.draw.rect(screen, GREEN, rect3, 7)

# 2. А теперь перемещаем сам прямоугольник rect3, а не создаём новый (т.е. переменная не меняется)
rect3.move_ip(50, 50)
pg.draw.rect(screen, YELLOW, rect3, 7)

# 3. Создадим прямоугольник rect4, который будет объединением прямоугольников rect1 и rect2
rect4 = rect1.union(rect2)
pg.draw.rect(screen, BLUE, rect4, 3)

# 4. Создадим прямоугольник rect7, который будет объединением прямоугольников rect5 и rect6
rect5 = pg.Rect((700, 500, 200, 200))
rect6 = pg.Rect((800, 550, 200, 200))  # квадраты 200х200px
pg.draw.rect(screen, BLUE, rect5, 3)
pg.draw.rect(screen, YELLOW, rect6, 3)

rect7 = rect5.clip(rect6)
pg.draw.rect(screen, BLACK, rect7)  # область будет закрашена, т.к. не указана ширина контура

# 5. Проверим, содержится ли rect7 внутри rect5
if rect5.contains(rect7):
    print('yes')
else:
    print('no')
# => yes

# игровой цикл
run = True
while run:
    for event in pg.event.get():
        if event.type == pg.QUIT:
            run = False

    pg.display.flip()  # обновление экрана

pg.quit()
