import pygame
import math
# подготавливаем модули библиотеки к работе.
pygame.init()

# ----------------------------------------------------------------------
# СОЗДАНИЕ ОКНА
# ----------------------------------------------------------------------
WIDTH = 1000
HEIGHT = 700
screen = pygame.display.set_mode((WIDTH, HEIGHT))
pygame.display.set_caption("Простые геометрические фигуры")
# Таймер для ограничения частоты кадров.
clock = pygame.time.Clock()

# ----------------------------------------------------------------------
# ЦВЕТА В PYGAME
# ----------------------------------------------------------------------
# Цвет задаётся кортежем RGB: (красный, зелёный, синий). Каждое значение — целое число от 0 до 255.
BLACK = (0, 0, 0)
WHITE = (255, 255, 255)
GRAY = (128, 128, 128)
RED = (255, 0, 0)
GREEN = (0, 200, 0)
BLUE = (0, 100, 255)
LIGHT_BLUE = (0, 255, 255)
YELLOW = (255, 220, 0)
PURPLE = (150, 0, 255)
ORANGE = (255, 140, 0)

# ----------------------------------------------------------------------
# ЗАЛИВКА ФОНА
# ----------------------------------------------------------------------
# screen.fill() закрашивает всю поверхность фона screen указанным цветом.
screen.fill(LIGHT_BLUE)

# ----------------------------------------------------------------------
# СИСТЕМА КООРДИНАТ
# ----------------------------------------------------------------------
# В Pygame начало координат находится в левом верхнем углу окна.
# Ось x направлена вправо.
# Ось y направлена ВНИЗ, а не вверх, как в обычной системе координат.

# ----------------------------------------------------------------------
# ПРЯМАЯ ЛИНИЯ
# ----------------------------------------------------------------------
pygame.draw.line(
    screen,                  # — поверхность, на которой рисуем
    BLACK,                   # — цвет линии
    (100, 100),     # — координаты начала линии
    (400, 100),      # — координаты конца
    5                  # — толщина линии в пикселях (если толщину не указать, она будет равна 1 пикселю)
)

# ----------------------------------------------------------------------
# ЛОМАНАЯ ЛИНИЯ
# ----------------------------------------------------------------------
pygame.draw.lines(
    screen,                   # — поверхность
    BLUE,                     # — цвет
    False,             # — замыкать ли фигуру (True соединит последнюю точку с первой)
    [(500, 100), (600, 50), (700, 130), (800, 80)],  # — список координат точек
    4                   # — толщина линии
)

# Замкнутая ломаная линия.
pygame.draw.lines(
    screen,
    GREEN,
    True,
    [(850, 100), (930, 60), (970, 140)],
    4
)

# ----------------------------------------------------------------------
# СГЛАЖЕННЫЕ ЛИНИИ (у неё нельзя указать толщину: она всегда равна 1 пикселю)
# ----------------------------------------------------------------------
pygame.draw.aaline(
    screen,
    RED,
    (100, 180),
    (400, 180)
)

# pygame.draw.aalines() рисует сглаженную ломаную линию.
pygame.draw.aalines(
    screen,
    PURPLE,
    False,
    [(500, 180), (600, 130), (700, 210), (800, 160)]
)

# ----------------------------------------------------------------------
# ПРЯМОУГОЛЬНИК
# ----------------------------------------------------------------------
pygame.draw.rect(
    screen,
    RED,
    (100, 240, 200, 120),  # — (x, y, thickness, height) - координаты левого верхнего угла, ширина и высота прямоугольника
    0    # — толщина границы (если 0, то прямоугольник закрашен)
)

# Прямоугольник с рамкой.
pygame.draw.rect(
    screen,
    BLACK,
    (350, 240, 200, 120),
    5
)

# ----------------------------------------------------------------------
# КРУГ
# ----------------------------------------------------------------------
pygame.draw.circle(
    screen,            # — поверхность
    BLUE,              # — цвет
    (700, 300),  # — координаты центра круга
    60,         # — радиус
    0            # — толщина границы
)

# Окружность без заливки.
pygame.draw.circle(
    screen,
    BLACK,
    (880, 300),
    60,
    5
)

# ----------------------------------------------------------------------
# ПРОИЗВОЛЬНЫЙ МНОГОУГОЛЬНИК
# ----------------------------------------------------------------------
# Для многоугольника нужно минимум три точки.
pygame.draw.polygon(
    screen,
    PURPLE,
    [(100, 420), (180, 500), (260, 420)],  # — список координат вершин
    0
)

# Многоугольник с рамкой.
pygame.draw.polygon(
    screen,
    BLACK,
    [(350, 420), (450, 500), (550, 420)],
    5
)

# ----------------------------------------------------------------------
# ЭЛЛИПС
# ----------------------------------------------------------------------
pygame.draw.ellipse(
    screen,
    YELLOW,
    (100, 540, 220, 120),  # — левый верхний угол, ширина и высота прямоугольника, в который вписан эллипс
    0
)

# Эллипс с рамкой.
pygame.draw.ellipse(
    screen,
    BLACK,
    (370, 540, 220, 120),
    5
)

# ----------------------------------------------------------------------
# ДУГА
# ----------------------------------------------------------------------
# Дуга рисуется против часовой стрелки по эллипсу
# от угла start_angle до угла end_angle в радианах.
# Полный оборот равен 2 * math.pi радиан.
# math.pi — это половина оборота (180 градусов).
pygame.draw.arc(
    screen,
    RED,
    (650, 540, 250, 120),  # — прямоугольник, в который вписан эллипс
    0,                # — начальный угол в радианах
    math.pi,                   # — конечный угол в радианах
    5                    # — толщина дуги
)

# ----------------------------------------------------------------------
# ОБНОВЛЕНИЕ ЭКРАНА
# ----------------------------------------------------------------------
# Все команды рисования сначала изменяют буфер изображения, а не сразу видимое окно.
# Чтобы показать нарисованное, нужно обновить экран:
# pygame.display.update() — обновляет весь экран или указанную часть экрана;
# pygame.display.flip() — всегда обновляет ВЕСЬ экран.
pygame.display.flip()

# ----------------------------------------------------------------------
# ОСНОВНОЙ ЦИКЛ
# ----------------------------------------------------------------------
running = True
while running:
    # Ограничиваем частоту смены кадров 60 кадрами в секунду.
    clock.tick(60)
    # Перебираем события окна.
    for event in pygame.event.get():
        # Событие QUIT возникает при нажатии на крестик.
        if event.type == pygame.QUIT:
            running = False

    # Здесь можно добавлять изменение координат фигур.
    # Например, если фигуры будут двигаться,
    # их нужно перерисовывать на каждом кадре.


    # Обновляем экран после всех изменений.
    pygame.display.flip()

# Завершаем работу Pygame после выхода из цикла.
pygame.quit()
