# Работа с поверхностями и изображениями в Pygame: класс Surface и модуль image
#---------------------------------------------------------------------------------------------------------
import pygame as pg
pg.init()


# зададим нужные цвета в формате RGB-кортежей
BLACK = (0, 0, 0)
WHITE = (255, 255, 255)
GRAY = (128, 128, 128)
RED = (255, 0, 0)
GREEN = (0, 200, 0)
BLUE = (0, 100, 255)
LIGHT_BLUE = (0, 255, 255)
YELLOW = (255, 220, 0)
PURPLE = (150, 0, 255)
ORANGE = (255, 140, 0)


'''
Создадим главное игровое окно  размером 1000х700px. Дадим название окну "Поверхности в Pygame".
Размеры окна лучше задавать в отдельных переменных, чтобы в дальнейшем использовать их в программе 
для контроля расположения объектов или для быстрого расширения окна
'''
W, H = 1000, 700
screen = pg.display.set_mode((W, H))
pg.display.set_caption("Поверхности в Pygame")

screen.fill(WHITE)  # заливка фона белым цветом

#---------------------------------------------------------------------------------------------------------
# ПОВЕРХНОСТИ В PYGAME
#---------------------------------------------------------------------------------------------------------
'''
Surface — это поверхность, какой-либо слой. Его можно представить как «холст»: 
на нём можно рисовать фигуры, загружать картинки, менять пиксели, цвета и выводить результат на экран.
Главное окно screen - это тоже поверхность => к нему можно применять все ниже рассмотренные методы
По умолчанию поверхность чёрная и пустая. Чтобы закрасить её цветом, можно использовать метод для заливки .fill()
'''
green_surf = pg.Surface((350, 200))  # поверхность размером 350x200px сохранили в переменную green_surf
green_surf.fill(GREEN)  # закрасили её зелёным цветом
'''
метод .set_alpha(k) делает поверхность и объекты на ней прозрачными (коэффициент прозрачности 0 <= k <= 255)
# при k = 0 поверхность полностью прозрачная (невидимая), при k = 255 поверхность совсем не прозрачная
'''
green_surf.set_alpha(150)  # сделали нашу поверхность полупрозрачной - объекты под поверхностью видно

# нарисуем вдоль экрана линию - под поверхностью её будет видно из-за прозрачности
pg.draw.line(screen, BLACK, (0, 520), (W, 520), 10)

# ----------------------------------------------------------------------
# РИСОВАНИЕ НА ПОВЕРХНОСТИ
# ----------------------------------------------------------------------
'''
Первым аргументом всех функций pygame.draw указывают поверхность, на которой нужно рисовать.
Поэтому можно рисовать не только на screen, но и на любой другой поверхности.
В Pygame объекты рисуются в том порядке, в котором вызываются команды. 
То, что нарисовано позже, перекрывает более ранний рисунок
'''
pg.draw.circle(green_surf, YELLOW, (100, 100), 50)  # русуем на нашей поверхности жёлтый круг
pg.draw.rect(green_surf, RED, (350 // 2 - 50, 200 // 2 - 50, 100, 100))  # рисуем поверх красный квадрат - он перекроет часть круга

# ----------------------------------------------------------------------
# ВЫВОД ПОВЕРХНОСТИ НА ЭКРАН
# ----------------------------------------------------------------------
'''
Созданная поверхность не появляется на экране автоматически. Её нужно отобразить при помощи метода .blit()
root.blit(source, destination) - выводит (отображает) одну поверхность на другую.

# source - что выводим;
# root - куда выводим;
# destination - в каких координатах.

координаты destination можно задавать:
# кортежем (x, y): координаты, в которых будет находиться левый верхний угол поверхности;
# объектом Rect - рассмотрим позже.

Повехность можно выводить только после всех выполненных изменений
'''
screen.blit(green_surf, (W // 2, H // 2))  # выводим нашу поверхность в середине экрана

# Одну и ту же поверхность можно вывести несколько раз. При этом сама поверхность green_surf не изменяется.
screen.blit(green_surf, (0, 0))  # выводим нашу поверхность в левом верхнем углу экрана

# ----------------------------------------------------------------------
# РАБОТА С ИЗОБРАЖЕНИЯМИ
# ----------------------------------------------------------------------
'''
Загруженные картинки тоже являются поверхностями, поэтому с ними нужно работать по тем же правилам.
Сайт с png-картинками: pngwing.com
Загрузим в программу картинки с помощью функции load(). Для этого сначала внутри нашего проекта создадим
папку images, в которой будут храниться все используемые картинки. А затем в функции load() в качестве
аргумента укажем путь к нужной картинке. Отобразим картинку на основном экране screen в самом верхнем правом углу.
Помните, что в методе blit() в качестве второго аргумента указываются координаты левого верхнего угла картинки.
'''
my_car = pg.image.load("images/orange_car.png")  # загружаем картинку
w_im, h_im = my_car.get_size()  # получаем размеры рамки, в которой заключена картинка
screen.blit(my_car, (W - w_im - 5, 0))  # отображаем картинку в главном окне screen

'''
Модуль pygame.transform содержит функции для изменения поверхностей. Некоторые трансформации (например, 
изменение размера) приводят к ухудшению изображения из-за потери части пикселей.
Функции модуля transform, которые изменяют поверхности, возвращают новые. Первым аргументом им передается 
изменяемая поверхность Surface. Рассмотрим на примере картинки с машиной.
'''
car_area = pg.Surface((300, 300))  # создаём доп поверхность размером 200x200
car_area.fill(WHITE)
w_new, h_new = car_area.get_size()  # получаем размеры нашей поверхности

my_car1 = pg.transform.scale(my_car, (70, 70))  # изменяем размер на 70x70

my_car2 = pg.transform.flip(my_car1, False, True)  # поворачиваем машину по оси Oy (зеркально отображаем сверху вниз)
my_car3 = pg.transform.flip(my_car1, True, False)  # поворачиваем машину по оси Ox (зеркально отображаем слева направо)

my_car4 = pg.transform.rotate(my_car1, 90)  # поворачиваем машину влево на 90 градусов
my_car5 = pg.transform.rotate(my_car1, -90)  # поворачиваем машину вправо на 90 градусов
my_car6 = pg.transform.rotate(my_car1, 180)  # поворачиваем машину влево на 180 градусов

# выводим машинки на поверхность car_area
car_area.blit(my_car1, (10, 10))      # 70×70 - уменьшенная копия исходной картинки
car_area.blit(my_car2, (110, 10))
car_area.blit(my_car3, (210, 10))
car_area.blit(my_car4, (10, 110))
car_area.blit(my_car5, (110, 110))
car_area.blit(my_car6, (210, 110))

screen.blit(car_area, (0, H - h_new))  # отображаем доп поверхность в главном окне

# игровой цикл
run = True
while run:
    for event in pg.event.get():
        if event.type == pg.QUIT:
            run = False

    pg.display.flip()  # обновляем изменения на экране

pg.quit()  # закрываем окно при завершении цикла
