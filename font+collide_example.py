#------------------------------------------------------
# ТЕКСТ И ОБРАБОТКА СТОЛКНОВЕНИЙ В PYGAME
#------------------------------------------------------
import pygame as pg
pg.init()

# цвета в формате RGB
WHITE = (255, 255, 255)
BLACK = (0, 0, 0)
BLUE = (50, 120, 240)
RED = (230, 70, 70)
GREEN = (70, 190, 100)
GRAY = (160, 160, 160)
YELLOW = (255, 220, 70)

# Создаём главное окно
W, H = 1200, 800
screen = pg.display.set_mode((W, H))
pg.display.set_caption("Обработка столкновений")
clock = pg.time.Clock()  # таймер игры

 # Задаём шрифт текста в игре (можно брать системные - класс SYSFont(семейство, размер, жирный, курсив), можно свои в файлах .otf - тогда используем класс Font(файл, размер)
font = pg.font.SysFont("arial", 25, True, False)

# Игрок - подвижный квадрат
player = pg.Rect(80, 250, 80, 80)

# Создадим ещё один квадрат - неподвижное препятствие
obstacle = pg.Rect(420, 220, 200, 200)

# Прямоугольник - имитация кнопки для проверки щелчка мышью.
button = pg.Rect(60, 480, 280, 70)

# Пока кнопка, игрок и препятствия - невидимы, так как это объекты класса Rect - прямоугольные области, которые не отображаются на экране


STEP = 5  # Создаём шаг - за одно нажатие квадрат перемещается на 5 пикселей.
button_active = False  # изначально, при запуске игры, на кнопку мы ещё не нажимали
click_message = "Щёлкните по кнопке или рядом с ней."  # начальное сообщение для кнопки


# функция для отображения текста на экране (чтобы не повторять одни и те же действия для каждой надписи)
# начальные данные - текст, координаты для размещения, цвет текста
def draw_text(text, x, y, color):
    image = font.render(text, True, color)  # создаём картинку с надписью шрифтом font (второй аргумент - сглаживание текста)
    screen.blit(image, (x, y))  # отображаем текст в главном окне screen


# Игровой цикл
running = True
while running:

    # ------------------------------------------
    # 1. Обработка событий
    # ------------------------------------------
    for event in pg.event.get():
        # при нажатии на крестик закрываем окно
        if event.type == pg.QUIT:
            running = False

        # обработка событий клавиатуры (одиночное нажатие без удержания кнопок)
        elif event.type == pg.KEYDOWN:
            # при нажатии на ESC завершаем игру
            if event.key == pg.K_ESCAPE:
                running = False
            # при нажатии на пробел возвращаем игрока в исходное положение
            elif event.key == pg.K_SPACE:
                player.topleft = (80, 250)
       
        # обработка событий мыши (одиночное нажатие без удержания кнопок)
        # 1 — левая кнопка мыши; 2 — средняя (центральная) кнопка; 3 — правая кнопка; 4 — прокрутка колёсика вверх; 5 — прокрутка колёсика вниз. 
        # event.pos — координаты мыши в момент нажатия.
        elif event.type == pg.MOUSEBUTTONDOWN:
            # Проверяем только левую кнопку мыши.
            if event.button == 1:
                # collidepoint() - проверка столкновения области с точкой
                # возвращает True, если точка находится внутри кнопки, иначе False
                if button.collidepoint(event.pos):
                    button_active = not button_active  # если кнопка была активной - делаем неактивной, и наоборот
                    click_message = "Щелчок внутри кнопки."
                else:
                    click_message = "Щелчок за пределами кнопки."

                print(click_message)

    # ------------------------------------------
    # 2. Организуем движение игрока-квадрата
    # ------------------------------------------
    p_key = pg.key.get_pressed()  # список состояний кнопок на клавиатуре True/False (с обработкой удержания кнопок)
    # проверяем нажатие на стрелки
    if p_key[pg.K_LEFT]:
        player.left -= STEP
    elif p_key[pg.K_RIGHT]:
        player.right += STEP
    elif p_key[pg.K_UP]:
        player.top -= STEP
    elif p_key[pg.K_DOWN]:
        player.top += STEP

    # ------------------------------------------
    # 3. Не даём игроку-квадрату выйти за границы окна
    # ------------------------------------------
    if player.left < 0:
        player.left = 0
    if player.right > W:
        player.right = W
    if player.top < 0:
        player.top = 0
    if player.bottom > H:
        player.bottom = H

    # ------------------------------------------
    # 4. Проверка пересечения прямоугольников
    # ------------------------------------------
    # colliderect() - обработка столкновения двух прямоугольных областей, возвращает: True — прямоугольники перекрываются; False — не перекрываются.
    collision = player.colliderect(obstacle)
    if collision:
        player_color = RED  # меняем цвет игрока на красный
        collision_message = "Прямоугольники пересекаются."
    else:
        player_color = BLUE  # меняем цвет игрока на синий
        collision_message = "Пересечения нет."

    # ------------------------------------------
    # 5. Отрисовка всех объектов на экране
    # ------------------------------------------
    screen.fill(WHITE)  # заливка фона белым

    # вывод сообщений при помощи ранее созданной функции draw_text()
    draw_text("Стрелки — перемещение квадрата.", 30, 20, BLACK)
    draw_text("Пробел — вернуть квадрат. Escape — выход.", 30, 55, BLACK)

    status_color = RED if collision else BLACK  # цвет надписи зависит от того, было ли столкновение игрока с препятствием
    draw_text(collision_message, 30, 105, status_color)

    # Сначала рисуем препятствие, затем квадрат (закрашенные, ширина контура не указана)
    pg.draw.rect(screen, GRAY, obstacle)
    pg.draw.rect(screen, player_color, player)

    # Отдельно рисуем контуры - они помогают видеть границы объектов
    pg.draw.rect(screen, BLACK, obstacle, 2)
    pg.draw.rect(screen, BLACK, player, 2)

    # Рисуем кнопку
    button_color = GREEN if button_active else YELLOW  # Цвет кнопки меняется после щелчка по ней
    pg.draw.rect(screen, button_color, button)
    pg.draw.rect(screen, BLACK, button, 2)

    # Отображаем текст на кнопке
    draw_text("Нажми на меня", button.x + 35, button.y + 20, BLACK)
    draw_text(click_message, 60, 570, BLACK)

    # обновляем экран и задаём частоту кадров не более 60 кадр/сек
    pg.display.flip()
    clock.tick(60)

pg.quit()
